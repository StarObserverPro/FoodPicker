export const OPENERS = Object.freeze(TOPICS.flatMap(([topic, lines]) => lines.map((text, index) => Object.freeze({
  id: `${topic}-${String(index + 1).padStart(2, '0')}`,
  text,
  topic,
}))));

/** Select an unseen local sentence; after all are seen, begin another cycle. */
export function chooseOpener({ seenIds = [], random = Math.random } = {}) {
  const seen = new Set(Array.isArray(seenIds) ? seenIds : []);
  const unseen = OPENERS.filter((entry) => !seen.has(entry.id));
  const pool = unseen.length ? unseen : OPENERS;
  const draw = typeof random === 'function' ? Number(random()) : 0;
  const unit = Number.isFinite(draw) ? Math.max(0, Math.min(0.9999999999999999, draw)) : 0;
  return pool[Math.floor(unit * pool.length)];
}
